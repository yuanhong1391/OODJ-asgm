    private void loadRoster()
    {
        File file = new File("roster.txt");
        rosterList.setText("");
        
        if(!file.exists())
        {
            rosterList.setText("No roster records found");
            return;
        }
        
        try
        {
            Scanner input = new Scanner(file);
            while(input.hasNextLine())
            {
                String line = input.nextLine();
                rosterList.append(line+"\n");
            }
            input.close();
        }
        
        catch(IOException e)
        {
            JOptionPane.showMessageDialog(this,"Unable to read records");
        }
    }

