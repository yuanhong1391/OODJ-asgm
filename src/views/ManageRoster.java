    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String rosterID = txtRosterID.getText().trim().toUpperCase();
        String doctorID = txtDoctorID.getText().trim().toUpperCase();
        String shiftDate = txtShiftDate.getText().trim();
        String shiftType = cmbShiftType.getSelectedItem().toString();
        
        //check empty 
        if(rosterID.isEmpty()||doctorID.isEmpty()||shiftDate.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Please complete all fields");
            return;
        }
        
        //check ID
        if(!rosterID.matches("R\\d{3}"))
        {
            JOptionPane.showMessageDialog(this, "RosterID must be RXXX");
            txtRosterID.requestFocus();
            return;
        }
        if(!doctorID.matches("D\\d{3}"))
        {
            JOptionPane.showMessageDialog(this, "DoctorID must be DXXX");
            txtDoctorID.requestFocus();
            return;
        }
        
        if(rosterIDExists(rosterID))
        {
            JOptionPane.showMessageDialog(this, "RosterID already exists");
            txtRosterID.requestFocus();
            return;
        }
        
        if(!ValidDate(shiftDate))
        {
            JOptionPane.showMessageDialog(this,"Please enter a valid date.Example:dd/mm/yyyy");
            txtShiftDate.requestFocus();
            return;
        }
        
        if(shiftExists(doctorID,shiftDate,shiftType))
        {
            JOptionPane.showMessageDialog(this, "This doctor already have same shift on this date");
            return;
        }
        
        try
        {
            FileWriter writer = new FileWriter("roster.txt",true);
            writer.write("RosterID:"+rosterID+"\n");
            writer.write("DoctorID:"+doctorID+"\n");
            writer.write("ShiftDate:"+shiftDate+"\n");
            writer.write("ShiftType:"+shiftType+"\n");
            writer.close();
            JOptionPane.showMessageDialog(this, "Roster added successfully");
            
            txtRosterID.setText("");
            txtDoctorID.setText("");
            txtShiftDate.setText("");
            cmbShiftType.setSelectedIndex(0);
            
            loadRoster();
        }
        
        catch(IOException e)
        {
            JOptionPane.showMessageDialog(this,"Unable to add the roster");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        String rosterID = txtRosterID.getText().trim().toUpperCase();
        String doctorID = txtDoctorID.getText().trim().toUpperCase();
        String shiftDate = txtShiftDate.getText().trim();
        String shiftType = cmbShiftType.getSelectedItem().toString();
        
        //check empty
        if(rosterID.isEmpty()||doctorID.isEmpty()||shiftDate.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Please complete all fields");
            return;
        }
        
        //check ID
        if(!rosterID.matches("R\\d{3}"))
        {
            JOptionPane.showMessageDialog(this, "RosterID must be RXXX");
            txtRosterID.requestFocus();
            return;
        }
        if(!doctorID.matches("D\\d{3}"))
        {
            JOptionPane.showMessageDialog(this, "DoctorID must be DXXX");
            txtDoctorID.requestFocus();
            return;
        }
        
        //check Date and Type
        if(!ValidDate(shiftDate))
        {
            JOptionPane.showMessageDialog(this,"Please enter a valid date.Example:dd/mm/yyyy");
            txtShiftDate.requestFocus();
            return;
        }
        if(shiftExistsForUpdate(rosterID,doctorID,shiftDate,shiftType))
        {
            JOptionPane.showMessageDialog(this,"This doctor already has a same Shift on this date");
            return;
        }
        
        File file = new File("roster.txt");
        if(!file.exists())
        {
            JOptionPane.showMessageDialog(this, "No roster record found");
            return;
        }
        
        StringBuilder updateData = new StringBuilder();
        boolean rosterFound = false;
        
        try
        {
            Scanner input = new Scanner(file);
            
            while(input.hasNextLine())
            {
                String line = input.nextLine();
                
                if(line.equalsIgnoreCase("RosterID:"+rosterID))
                {
                    rosterFound = true;
                    updateData.append("RosterID:"+rosterID+"\n");
                    
                    if(input.hasNextLine())
                    {
                        input.nextLine();
                    }
                    
                    if(input.hasNextLine())
                    {
                        input.nextLine();
                    }
                    if(input.hasNextLine())
                    {
                        input.nextLine();
                    }
                    updateData.append("DoctorID:"+doctorID+"\n");
                    updateData.append("ShiftDate:"+shiftDate+"\n");
                    updateData.append("ShiftType:"+shiftType+"\n");
                }
                else
                {
                    updateData.append(line+"\n");
                }
            }
            input.close();
            
            if(!rosterFound)
            {
                JOptionPane.showMessageDialog(this,"RosterID not Found");
                return;
            }
            
            FileWriter writer = new FileWriter("roster.txt");
            writer.write(updateData.toString());
            writer.close();
            JOptionPane.showMessageDialog(this,"Roster updated successfully");
            
            txtRosterID.setText("");
            txtDoctorID.setText("");
            txtShiftDate.setText("");
            cmbShiftType.setSelectedIndex(0);
            
            loadRoster();
        }
        catch(IOException e)
        {
            JOptionPane.showMessageDialog(this,"Unable to update the roster");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private boolean ValidDate(String shiftDate)
    {
        if(!shiftDate.matches("\\d{2}/\\d{2}/\\d{4}"))
        {
            return false;
        }
        SimpleDateFormat format = new SimpleDateFormat("dd/MM/yyyy");
        format.setLenient(false);
        
        try
        {
            format.parse(shiftDate);
            return true;
        }
        
        catch(ParseException e)
        {
            return false;
        }
    }
        
    private boolean rosterIDExists(String rosterID)
    {
        File file = new File("roster.txt");
        
        if(!file.exists())
        {
            return false;
        }
        
        try
        {
            Scanner input = new Scanner(file);
            
            while(input.hasNextLine())
            {
                String line = input.nextLine().trim();
                
                
                if(line.equalsIgnoreCase("RosterID:"+rosterID))
                {
                    input.close();
                    return true;
                }
            }
        input.close();
        }
        catch(IOException e)
        {
            JOptionPane.showMessageDialog(this,"Unable to read records");
        }
        return false;
    } 
    
    private boolean shiftExists(String doctorID,String shiftDate,String shiftType)
    {
        File file = new File("roster.txt");
        
        if(!file.exists())
        {
            return false;
        }
        try
        {
            Scanner input = new Scanner(file);
            
            while(input.hasNextLine())
            {
                String line = input.nextLine().trim();
                if(line.startsWith("RosterID:"))
                {
                    //Read line
                    String doctorLine = input.nextLine().trim();
                    String dateLine = input.nextLine().trim();
                    String shiftLine = input.nextLine().trim();
                    
                        //compare with user input to check
                        if((doctorLine.equalsIgnoreCase("DoctorID:" + doctorID)
                           &&dateLine.equalsIgnoreCase("ShiftDate:" + shiftDate)
                           && shiftLine.equalsIgnoreCase("ShiftType:" + shiftType)))
                        {
                            input.close();
                            return true;
                        }
                }
            }
            input.close();
        }
        catch(IOException e)
        {
            JOptionPane.showMessageDialog(this,"Unable to check existing shifts");
        }
        return false;
    }
    
    private boolean shiftExistsForUpdate(String rosterID,String doctorID,String shiftDate,String shiftType)
    {
    File file = new File("roster.txt");

    if(!file.exists())
    {
        return false;
    }

    try
    {
        Scanner input = new Scanner(file);

        while(input.hasNextLine())
        {
            String rosterLine = input.nextLine().trim();

            if(rosterLine.startsWith("RosterID:"))
            {
                String doctorLine = input.nextLine().trim();
                String dateLine = input.nextLine().trim();
                String shiftLine = input.nextLine().trim();

                // Ignore the roster currently being updated
                if(!rosterLine.equalsIgnoreCase("RosterID:" + rosterID))
                {
                    if(doctorLine.equalsIgnoreCase("DoctorID:" + doctorID)
                       &&dateLine.equalsIgnoreCase("ShiftDate:" + shiftDate)
                       &&shiftLine.equalsIgnoreCase("ShiftType:" + shiftType))
                    {
                        input.close();
                        return true;
                    }
                }
            }
        }

        input.close();
    }
    catch(IOException e)
    {
        JOptionPane.showMessageDialog(this,
                "Unable to check existing shifts");
    }

    return false;
}
